const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('src/components/ProfilesView.js', 'utf8').replace(/^import .*;\r?\n/gm, '');
const component = import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
test('cleanup follows displayed order, awaits each result, skips running and continues after errors', async () => {
  const { ProfilesViewComponent } = await component;
  const view = Object.create(ProfilesViewComponent.prototype);
  view.profiles = [{id:'a'}, {id:'b'}, {id:'running',status:'running'}, {id:'c'}, {id:'d'}];
  view.container = {querySelector:()=>null};
  const states = [], calls = [];
  view.updateProfileRowStatus = id => states.push([id, view.cleanupStatuses.get(id)?.state]);
  global.requestAnimationFrame = callback => callback();
  global.alert = () => {};
  let release;
  global.window = {api:{freeDiskSpace: async id => {
    calls.push(id);
    if(id==='b') await new Promise(resolve=>{release=resolve});
    if(id==='c') throw Error('disk error');
    if(id==='d') return {success:false,message:'permission denied'};
    return {success:true,freedBytes:1048576};
  }}};
  const targets = [view.profiles[1],view.profiles[0],...view.profiles.slice(2)];
  const promise = view.runBulkCleanup(targets,'disk');
  while(!release) await new Promise(resolve=>setTimeout(resolve,1));
  assert.deepEqual(calls,['b']);
  assert.equal(view.cleanupStatuses.get('b').state,'working');
  assert.equal(view.cleanupStatuses.has('a'),false);
  assert.equal(await view.runBulkCleanup(targets,'disk'),undefined);
  release();
  const summary = await promise;
  assert.deepEqual(calls,['b','a','c','d']);
  assert.deepEqual(summary,{success:2,skipped:1,failed:2,freedBytes:2097152});
  assert.deepEqual(states.filter(([,state])=>state).map(([id,state])=>id+':'+state),['b:working','b:success','a:working','a:success','running:skipped','c:working','c:failed','d:working','d:failed']);
  assert.equal(view.profiles[2].status,'running');
  assert.equal(view.profiles[0].status,undefined);
  assert.equal(view._bulkCleanupRunning,false);
  assert.match(view.getStatusHtml(view.profiles[2],true),/Bỏ qua: đang mở/);
});
test('cache uses its own IPC and reports failure rather than false success when unavailable', async()=>{
  const { ProfilesViewComponent }=await component;
  const view=Object.create(ProfilesViewComponent.prototype);
  view.profiles=[{id:'one'}]; view.updateProfileRowStatus=()=>{};
  const btn={disabled:false};view.container={querySelector:()=>btn};
  let calls=0;global.window={api:{clearCache:async()=>{calls++;return {success:true,freedBytes:0}}}};
  const result=await view.runBulkCleanup(view.profiles,'cache');
  assert.equal(calls,1);assert.equal(result.success,1);assert.equal(btn.disabled,false);
  global.window.api={};
  const missing=await view.runBulkCleanup(view.profiles,'cache');
  assert.equal(missing.failed,1);assert.equal(missing.success,0);
});
